import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { parseHTML } from "linkedom";

/**
 * Builds the page-icon catalog from Phosphor's LIGHT weight.
 *
 * Run `node scripts/build-page-icons.mjs` to rewrite
 * `app/components/pageIcons.ts`. Sibling of `build-icons.mjs`, which curates a
 * much smaller set for the canvas; this one takes the whole weight, because a
 * page icon is chosen by searching for a subject rather than picked off a short
 * list, and a short list is what made the first attempt read as a menu of
 * commands rather than a set of subjects.
 *
 * Light rather than thin, regular or fill. Thin is Phosphor's finest weight and
 * it was too fine here: at the 14px a sidebar row draws, a 1px hairline nearly
 * disappears against the page. Light is one step up — 1.5px on the 24 grid,
 * still a fine outline and still the same drawing — and it holds at row size.
 * Regular and fill both read as heavy beside text.
 *
 * Source: Phosphor (MIT), 256-box, drawn as filled outlines — the line is the
 * shape, not a stroke, so these paint with `fill` and no `stroke`.
 *
 * Path data only, converted at BUILD time: the runtime never parses an icon
 * body. An icon carrying anything but paths is skipped by name rather than
 * silently half-drawn.
 */

const require = createRequire(import.meta.url);
const ph = require("@iconify-json/ph/icons.json");
const OUT = "app/components/pageIcons.ts";

/**
 * Offered first, before the alphabet. Nothing is excluded by leaving a name out
 * — search reaches all of them — but a picker that opens on "acorn, activity,
 * address-book" reads as a dictionary, and these are what a page is usually
 * about.
 */
const SUGGESTED = [
  "rocket", "star", "flag", "target", "lightbulb", "heart", "lightning",
  "calendar-blank", "clock", "book-open", "notebook", "chart-line", "briefcase",
  "user", "users-three", "map-trifold", "compass", "map-pin", "leaf", "image",
  "images", "graph", "table", "code", "function", "chat-circle", "envelope",
  "folder", "file-text", "bookmark-simple", "tag", "wrench", "gear", "globe",
  "house", "shopping-cart", "currency-dollar", "trophy", "medal", "gift",
  "camera", "microphone", "music-notes", "film-slate", "palette", "pencil",
  "paperclip", "magnifying-glass", "shield-check", "lock-simple", "key",
  "warning", "check-circle", "question", "info",
];

/** Bare path data, or null when the body holds something we do not convert. */
function pathFor(body) {
  const { document } = parseHTML(`<svg>${body}</svg>`);
  const svg = document.querySelector("svg");
  const parts = [];
  for (const node of svg.children) {
    if (node.tagName.toLowerCase() !== "path") return null;
    const d = node.getAttribute("d");
    if (!d) return null;
    parts.push(d);
  }
  return parts.length ? parts.join(" ") : null;
}

const icons = {};
const skipped = [];
for (const [id, icon] of Object.entries(ph.icons)) {
  if (!id.endsWith("-light")) continue;
  const name = id.slice(0, -"-light".length);
  const d = pathFor(icon.body);
  if (!d) {
    skipped.push(name);
    continue;
  }
  icons[name] = d;
}

const names = Object.keys(icons).sort();
const suggested = SUGGESTED.filter((n) => {
  if (icons[n]) return true;
  console.warn(`  suggested but absent from the set, dropped: ${n}`);
  return false;
});

const file = `// Generated by scripts/build-page-icons.mjs — do not edit by hand.
// Source: Phosphor Light (MIT), 256-box, filled outlines.
//
// Lazy-loaded: nothing imports this from the shell. The picker pulls it when
// its Icons tab is first opened, and the chosen path travels with the icon, so
// drawing a row never needs the catalog.

/** The box every path here is drawn in. */
export const PAGE_ICON_BOX = ${ph.height ?? 256};

/** Offered before the alphabet — what a page is usually about. */
export const SUGGESTED_ICONS: readonly string[] = ${JSON.stringify(suggested)};

/** name → bare SVG path data. */
export const PAGE_ICONS: Record<string, string> = ${JSON.stringify(icons)};
`;

writeFileSync(OUT, file);
const kb = Math.round(file.length / 1024);
console.log(`${names.length} icons -> ${OUT} (${kb}KB)`);
console.log(`${suggested.length} suggested`);
if (skipped.length) console.log(`skipped ${skipped.length}: ${skipped.slice(0, 8).join(", ")}`);
